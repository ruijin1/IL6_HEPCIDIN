# -*- coding: utf-8 -*-
r"""MIMIC-III NICU: is the within-subject bilirubin decline specific to invasive infection?

Negative-control (falsification) analysis added during revision of the manuscript.

Rationale
  Coagulase-negative staphylococci (CoNS) account for about half of all positive blood cultures in the NICU and
  usually represent skin-flora contamination rather than bloodstream infection. If the 72 h decline in bilirubin
  after a positive culture were generated by the act of taking a culture (sicker infants, more sampling, more
  phototherapy) or by generic acute-phase severity, it should also appear after a CoNS-positive culture.
  If it is confined to cultures growing a definite pathogen, a generic artefactual explanation becomes less tenable.

Design (mirrors Table 1 of the manuscript)
  Pairs are rebuilt exactly as in 20261017_bilirubin_transfusion_robust.py, and the published estimates are
  reproduced before anything else is run.
  Three-level exposure: negative (reference) / CoNS-positive / definite-pathogen-positive.
  Models: (a) unadjusted; (b) adjusted for interval and baseline bilirubin; (c) as (b) plus transfusion.
  Estimator: OLS with HC3 robust standard errors, as elsewhere in the manuscript.

Output: F_bilirubin_conscocci_negative_control.csv
"""
import os, sys
sys.stdout.reconfigure(encoding="utf-8")
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

DIR = (sys.argv[1] if len(sys.argv) > 1 else
       os.environ.get("MIMIC_CSV_DIR", r"D:\workbuddy_workspace\03-data\MIMIC_NICU_iron"))
OUT = os.path.join(DIR, "F_bilirubin_conscocci_negative_control.csv")


def build_pairs():
    base = pd.read_csv(os.path.join(DIR, "nicu_base.csv"), encoding="utf-8-sig",
                       parse_dates=["dob", "intime"])
    lab = pd.read_csv(os.path.join(DIR, "nicu_cbc.csv"), encoding="utf-8-sig", parse_dates=["charttime"])
    cul = pd.read_csv(os.path.join(DIR, "nicu_culture.csv"), encoding="utf-8-sig", parse_dates=["charttime"])
    base = base[base.age_days_at_icu <= 28]
    cul = cul[cul.hadm_id.isin(base.hadm_id)]
    bili = lab[lab["var"] == "bili_total"][["hadm_id", "charttime", "valuenum"]].sort_values("charttime")
    rows = []
    for _, cu in cul.iterrows():
        g = bili[bili.hadm_id == cu.hadm_id]
        if not len(g):
            continue
        t0, t1 = cu.charttime, cu.charttime + pd.Timedelta(hours=72)
        pre = g[(g.charttime <= t0) & (g.charttime >= t0 - pd.Timedelta(hours=48))]
        post = g[(g.charttime > t0) & (g.charttime <= t1)]
        if not len(pre) or not len(post):
            continue
        cu_is_cons = int(("staphylococcus" in str(cu.orgs).lower())
                         or ("coagulase negative" in str(cu.orgs).lower()))
        rows.append(dict(hadm_id=cu.hadm_id, positive=int(cu.positive), cu_is_cons=cu_is_cons,
                         pre=pre.valuenum.iloc[-1], post=post.valuenum.iloc[0],
                         delta=post.valuenum.iloc[0] - pre.valuenum.iloc[-1],
                         gap_h=(post.charttime.iloc[0] - pre.charttime.iloc[-1]).total_seconds() / 3600))
    return pd.DataFrame(rows)


P = build_pairs()

# ---- Step 0: reproduce the published pairs and the published Table 1 estimates --------------------
ref = pd.read_csv(os.path.join(DIR, "D_bilirubin_pairs.csv"), encoding="utf-8-sig")
print("rebuilt pairs = %d ; published = %d ; positive = %d"
      % (len(P), len(ref), int(P.positive.sum())))

P["pos_definite"] = ((P.positive == 1) & (P.cu_is_cons == 0)).astype(int)
P["pos_cons"] = ((P.positive == 1) & (P.cu_is_cons == 1)).astype(int)
print("culture-positive pairs: definite pathogen %d, CoNS-only %d (sum %d of %d positive)"
      % (int(P.pos_definite.sum()), int(P.pos_cons.sum()),
         int(P.pos_definite.sum() + P.pos_cons.sum()), int(P.positive.sum())))

def fit(tag, d, formula, term="positive"):
    d = d.dropna(subset=["delta", "gap_h", "pre"])
    m = smf.ols(formula, data=d).fit(cov_type="HC3")
    ci = m.conf_int().loc[term]
    print("  %-52s n=%4d (cases %3d)  %+7.3f (%+7.3f, %+7.3f)  p=%.3g"
          % (tag, len(d), int(d[term].sum()), m.params[term], ci[0], ci[1], m.pvalues[term]))
    return dict(analysis=tag, term=term, n=len(d), ncase=int(d[term].sum()),
                b=m.params[term], lo=ci[0], hi=ci[1], p=m.pvalues[term])

res = []
print("\n-- reproduction of published Table 1 rows --")
res.append(fit("Main model (positive vs negative)", P, "delta ~ positive"))
res.append(fit("Adjusted for interval and baseline", P, "delta ~ positive + gap_h + pre"))
res.append(fit("Definite pathogen (reference = all negatives)", P, "delta ~ pos_definite + gap_h + pre",
               term="pos_definite"))

print("\n-- negative control: CoNS-only positive cultures --")
res.append(fit("CoNS-only (reference = all negatives)", P, "delta ~ pos_cons + gap_h + pre", term="pos_cons"))

print("\n-- three-level model, negative cultures as reference --")
P["grp"] = np.select([P.pos_definite == 1, P.pos_cons == 1], ["definite", "cons"], default="negative")
d3 = P.copy()
d3["g_definite"] = (d3.grp == "definite").astype(int)
d3["g_cons"] = (d3.grp == "cons").astype(int)
res.append(fit("Three-level: CoNS vs negative", d3, "delta ~ g_definite + g_cons + gap_h + pre", term="g_cons"))
res.append(fit("Three-level: definite pathogen vs negative", d3, "delta ~ g_definite + g_cons + gap_h + pre",
               term="g_definite"))
m3 = smf.ols("delta ~ g_definite + g_cons + gap_h + pre", data=d3).fit(cov_type="HC3")
from scipy import stats
diff = m3.params["g_definite"] - m3.params["g_cons"]
se = np.sqrt(m3.cov_params().loc["g_definite", "g_definite"] + m3.cov_params().loc["g_cons", "g_cons"]
             - 2 * m3.cov_params().loc["g_definite", "g_cons"])
p_diff = 2 * (1 - stats.norm.cdf(abs(diff / se)))
print("  difference definite - CoNS = %+.3f (SE %.3f), p = %.3f" % (diff, se, p_diff))
res.append(dict(analysis="Contrast: definite pathogen minus CoNS-only", term="difference", n=len(d3),
                ncase=np.nan, b=diff, lo=diff - 1.96 * se, hi=diff + 1.96 * se, p=p_diff))

print("\n-- supplementary: unadjusted group means --")
for g, gg in P.groupby("grp"):
    print("  %-9s n=%4d  mean delta %+6.2f (SD %5.2f)  mean pre %5.2f"
          % (g, len(gg), gg.delta.mean(), gg.delta.std(), gg.pre.mean()))

pd.DataFrame(res).to_csv(OUT, index=False, encoding="utf-8-sig")
print("\nsaved:", OUT)
